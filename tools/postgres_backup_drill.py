"""Synthetic PostgreSQL backup/restore exercise, invoked by the cluster runner."""

import json
from pathlib import Path

import psycopg

from postgres_backup import backup, restore_verify


def drill(pg_bin, options, database, output_directory):
    output_directory = Path(output_directory)
    with psycopg.connect(**options, dbname=database) as conn:
        # Dedicated synthetic tables cover the types and relationships most
        # likely to expose a lossy export or improperly restored sequence.
        conn.execute("""CREATE TABLE public.backup_drill_parent (
            id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            label text NOT NULL UNIQUE, details jsonb, created_at timestamptz,
            evidence bytea, amount numeric(12,3), optional text)""")
        conn.execute("""CREATE TABLE public.backup_drill_child (
            id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            parent_id bigint NOT NULL REFERENCES public.backup_drill_parent(id),
            label text NOT NULL CHECK (length(label) > 0))""")
        conn.execute("""INSERT INTO public.backup_drill_parent(label, details, created_at, evidence, amount, optional)
            VALUES (%s, %s, %s, %s, %s, NULL)""",
            ("Synthetic ỌAU — restore", json.dumps({"restored": True, "items": [1, None, "é"]}),
             "2026-10-21T09:30:00+01:00", b"\x00\xff\n\\", "12345.670"))
        conn.execute("INSERT INTO public.backup_drill_child(parent_id,label) VALUES (1,'Synthetic relation')")
    archive = output_directory / "synthetic-backup.dump"
    manifest = backup(pg_bin, options, database, archive)
    restored = restore_verify(pg_bin, options, archive)
    # A corrupted archive must be rejected before any restore/database mutation.
    corrupt = output_directory / "synthetic-corrupt.dump"
    data = bytearray(archive.read_bytes())
    data[-1] ^= 1
    corrupt.write_bytes(data)
    corrupt.with_suffix(".dump.json").write_text(archive.with_suffix(".dump.json").read_text(encoding="utf-8"), encoding="utf-8")
    try:
        try:
            restore_verify(pg_bin, options, corrupt)
        except ValueError as error:
            if "checksum" not in str(error):
                raise
        else:
            raise AssertionError("Corrupted backup was accepted")
    finally:
        corrupt.unlink(missing_ok=True)
        corrupt.with_suffix(".dump.json").unlink(missing_ok=True)
    report = {"synthetic_only": True, "archive": str(archive), "verified": restored["verified"],
              "tables": restored["tables"], "constraints": len(manifest["fingerprint"]["constraints"]),
              "sequences": len(manifest["fingerprint"]["sequences"]),
              "checksum_tamper_rejected": True, "source_database_untouched_by_restore": True,
              "pg_dump": manifest["pg_dump"], "server_version": manifest["server_version"]}
    (output_directory / "backup-drill-report.json").write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")
    print("Backup drill passed; source rows, foreign keys, identity sequences and checksum rejection verified.")
